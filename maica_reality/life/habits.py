def load():
    if os.path.exists(HABITS_FILE):
        with open(HABITS_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    return dict(默认习惯)


def save(habits=None):
    if habits is None:
        habits = load()
    os.makedirs(os.path.dirname(HABITS_FILE), exist_ok=True)
    with open(HABITS_FILE, "w", encoding="utf-8") as f:
        json.dump(habits, f, ensure_ascii=False, indent=2)


def init_if_needed():
    if not os.path.exists(HABITS_FILE):
        save(默认习惯)
        return 默认习惯
    return load()


def apply_grade_change(new_year, old_year=None):
    h = load()
    if "大二" in new_year:
        h["上课"]["Monika的课程"]["专业课"].append("毕业论文准备研讨")
    elif "大四" in new_year:
        h["上课"]["Monika的课程"]["专业课"] = ["毕业论文"]
        h["社团"]["备注"] = "卸任，交给后辈"
    save(h)
    return h


