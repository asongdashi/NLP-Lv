def update_from_feedback(changes):
    h = load()
    for dotted_key, new_val in changes.items():
        parts = dotted_key.split(".")
        target = h
        for p in parts[:-1]:
            target = target.setdefault(p, {})
        target[parts[-1]] = new_val
    save(h)
    return h


